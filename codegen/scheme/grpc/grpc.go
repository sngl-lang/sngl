// Package grpc writes the package a `grpc:` import resolves to: a struct per
// message, an enum per enum and a function per unary method, each marked
// with what sngl:grpc's call needs to write it as protobuf.
package grpc

import (
	"context"
	"encoding/base64"
	"errors"
	"fmt"
	"strconv"
	"strings"
	"unicode"

	"github.com/bufbuild/protocompile"
	protoast "github.com/bufbuild/protocompile/ast"
	protoparser "github.com/bufbuild/protocompile/parser"
	"github.com/bufbuild/protocompile/reporter"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"

	"duckfam.us/sngl/ast"
	"duckfam.us/sngl/internal/parser"
)

// Package is what an import of a `.proto` resolves to.
type Package struct {
	Source string
	Notes  []string
}

// reserved are the names the written package declares beside the file's.
var reserved = []string{"server", "descriptor"}

// reservedProps are the names an adapter's own props take.
var reservedProps = []string{"request", "value", "pending", "failure", "load", "fail", "refresh", "query"}

// Generate compiles files, the `.proto` files read by the name an import
// statement gives each, and writes the package of the one named name, read
// from the import path from.
func Generate(files map[string]string, name, from string) (*Package, error) {
	var errs []string
	c := protocompile.Compiler{
		Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
			Accessor: protocompile.SourceAccessorFromMap(files),
		}),
		SourceInfoMode: protocompile.SourceInfoStandard,
		Reporter: reporter.NewReporter(func(err reporter.ErrorWithPos) error {
			errs = append(errs, err.Error())
			return nil
		}, nil),
	}
	compiled, err := c.Compile(context.Background(), name)
	if len(errs) > 0 {
		return nil, errors.New(strings.Join(errs, "\n"))
	}
	if err != nil {
		return nil, fmt.Errorf("grpc:%s: %w", from, err)
	}
	w := newWriter(compiled[0], from)
	src, err := w.write()
	if err != nil {
		return nil, err
	}
	return &Package{Source: src, Notes: w.notes}, nil
}

// Imports are the files text imports that the handler reads: every one but
// those protobuf ships. A file that does not parse imports nothing, and
// Generate says why.
func Imports(text, name string) []string {
	f, err := protoparser.Parse(name, strings.NewReader(text), reporter.NewHandler(nil))
	if err != nil {
		return nil
	}
	var out []string
	for _, d := range f.Decls {
		if imp, ok := d.(*protoast.ImportNode); ok {
			if p := imp.Name.AsString(); !strings.HasPrefix(p, "google/protobuf/") {
				out = append(out, p)
			}
		}
	}
	return out
}

type writer struct {
	file  protoreflect.FileDescriptor
	from  string
	b     strings.Builder
	notes []string
	taken map[string]bool
	// types are the SNGL names of the messages and enums written, by full
	// name; order is the order they are written in.
	types map[protoreflect.FullName]string
	order []protoreflect.Descriptor
}

func newWriter(file protoreflect.FileDescriptor, from string) *writer {
	w := &writer{file: file, from: from, taken: map[string]bool{}, types: map[protoreflect.FullName]string{}}
	for _, r := range reserved {
		w.taken[strings.ToLower(r)] = true
	}
	return w
}

func (w *writer) note(format string, args ...any) {
	w.notes = append(w.notes, fmt.Sprintf(format, args...))
}

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteByte('\n')
}

func (w *writer) write() (string, error) {
	w.collect()
	w.line("// Code generated by the grpc: scheme from %s. DO NOT EDIT.", w.from)
	w.line("")
	w.line(`import async "sngl:async"`)
	w.line(`import grpc "sngl:grpc"`)
	w.line("")
	w.line("// Where the service is, `host:port` or `https://host`: provide it around")
	w.line("// the subtree, or the test, that calls it.")
	w.line(`context #server("")`)
	w.line("")
	w.line("// The FileDescriptorSet declaring the service, as base64: what a target")
	w.line("// running protoc's own generation is handed.")
	w.line("const descriptor = %s", quote(w.descriptorSet()))
	for _, d := range w.order {
		w.line("")
		switch d := d.(type) {
		case protoreflect.MessageDescriptor:
			w.message(d)
		case protoreflect.EnumDescriptor:
			w.enum(d)
		case protoreflect.OneofDescriptor:
			w.oneof(d)
		}
	}
	w.services()
	doc, err := parser.Parse("grpc.sngl", []byte(w.b.String()))
	if err != nil {
		return "", fmt.Errorf("grpc: the package written does not parse: %w", err)
	}
	return parser.Format(doc), nil
}

// collect names every message and enum the file declares, and every one its
// fields and methods reach from another file -- a well-known type -- each
// once.
func (w *writer) collect() {
	var visit func(d protoreflect.Descriptor)
	visit = func(d protoreflect.Descriptor) {
		if _, done := w.types[d.FullName()]; done {
			return
		}
		if m, ok := d.(protoreflect.MessageDescriptor); ok && m.IsMapEntry() {
			return
		}
		w.types[d.FullName()] = w.claimType(d)
		w.order = append(w.order, d)
		m, ok := d.(protoreflect.MessageDescriptor)
		if !ok {
			return
		}
		for i := range m.Oneofs().Len() {
			if o := m.Oneofs().Get(i); !o.IsSynthetic() {
				want := w.types[m.FullName()] + capital(camel(string(o.Name())))
				w.types[o.FullName()] = w.claim(want, func(to string) {
					w.note("oneof %s is declared as %s: %s is taken or reserved", o.FullName(), to, want)
				})
				w.order = append(w.order, o)
			}
		}
		for i := range m.Fields().Len() {
			f := m.Fields().Get(i)
			if f.IsMap() {
				f = f.MapValue()
			}
			if f.Message() != nil {
				visit(f.Message())
			}
			if f.Enum() != nil {
				visit(f.Enum())
			}
		}
		for i := range m.Enums().Len() {
			visit(m.Enums().Get(i))
		}
		for i := range m.Messages().Len() {
			visit(m.Messages().Get(i))
		}
	}
	for i := range w.file.Enums().Len() {
		visit(w.file.Enums().Get(i))
	}
	for i := range w.file.Messages().Len() {
		visit(w.file.Messages().Get(i))
	}
	for i := range w.file.Services().Len() {
		s := w.file.Services().Get(i)
		for j := range s.Methods().Len() {
			visit(s.Methods().Get(j).Input())
			visit(s.Methods().Get(j).Output())
		}
	}
}

// claimType names a message or an enum: its name, after the names of the
// messages it is nested in, `Book.Shelf` → `BookShelf`.
func (w *writer) claimType(d protoreflect.Descriptor) string {
	pkg := d.ParentFile().Package()
	rel := strings.TrimPrefix(string(d.FullName()), string(pkg)+".")
	var want strings.Builder
	for part := range strings.SplitSeq(rel, ".") {
		want.WriteString(capital(camel(part)))
	}
	return w.claim(want.String(), func(to string) {
		w.note("%s is declared as %s: %s is taken or reserved", d.FullName(), to, want.String())
	})
}

// claim takes want, or the first free name made from it. Two names
// differing only in case are one: Go exports both as one identifier.
func (w *writer) claim(want string, renamed func(to string)) string {
	got := want
	if parser.LookupIdent(got) != parser.IDENT {
		got += "_"
	}
	for i := 2; w.taken[strings.ToLower(got)]; i++ {
		got = want + strconv.Itoa(i)
	}
	w.taken[strings.ToLower(got)] = true
	if got != want && renamed != nil {
		renamed(got)
	}
	return got
}

// descriptorSet is the file and every file it imports, as base64 of a
// FileDescriptorSet, dependencies first.
func (w *writer) descriptorSet() string {
	set := &descriptorpb.FileDescriptorSet{}
	seen := map[string]bool{}
	var add func(f protoreflect.FileDescriptor)
	add = func(f protoreflect.FileDescriptor) {
		if seen[f.Path()] {
			return
		}
		seen[f.Path()] = true
		for i := range f.Imports().Len() {
			add(f.Imports().Get(i).FileDescriptor)
		}
		fp := protodesc.ToFileDescriptorProto(f)
		fp.SourceCodeInfo = nil
		set.File = append(set.File, fp)
	}
	add(w.file)
	b, err := proto.MarshalOptions{Deterministic: true}.Marshal(set)
	if err != nil {
		panic("grpc: a compiled file has no descriptor: " + err.Error())
	}
	return base64.StdEncoding.EncodeToString(b)
}

func (w *writer) comment(d protoreflect.Descriptor) {
	loc := d.ParentFile().SourceLocations().ByDescriptor(d)
	text := strings.TrimSpace(loc.LeadingComments)
	if text == "" {
		return
	}
	for l := range strings.SplitSeq(text, "\n") {
		if l = strings.TrimSpace(l); l == "" {
			w.line("//")
		} else {
			w.line("// %s", l)
		}
	}
}

func (w *writer) message(m protoreflect.MessageDescriptor) {
	w.comment(m)
	w.line("#[grpc.message(%s)]", quote(string(m.FullName())))
	w.line("struct %s {", w.types[m.FullName()])
	fields := map[string]bool{}
	written := map[protoreflect.FullName]bool{}
	for i := range m.Fields().Len() {
		f := m.Fields().Get(i)
		if o := f.ContainingOneof(); o != nil && !o.IsSynthetic() {
			if !written[o.FullName()] {
				written[o.FullName()] = true
				typ := w.types[o.FullName()]
				w.comment(o)
				w.line("%s %s = %s.%s", fieldName(fields, camel(string(o.Name())), func(to string) {
					w.note("oneof %s is %s", o.FullName(), to)
				}), typ, typ, oneofNone)
			}
			continue
		}
		typ, kind, why := w.fieldType(f)
		if why != "" {
			w.note("field %s of %s is left out: %s", f.Name(), m.FullName(), why)
			continue
		}
		want := f.JSONName()
		if want == "" {
			want = camel(string(f.Name()))
		}
		name := fieldName(fields, want, func(to string) {
			w.note("field %s of %s is %s", f.Name(), m.FullName(), to)
		})
		w.comment(f)
		if kind != "" {
			w.line("#[grpc.field(%d, %s)]", f.Number(), kind)
		} else {
			w.line("#[grpc.field(%d)]", f.Number())
		}
		if def := w.zero(f, typ); def != "" {
			w.line("%s %s = %s", name, typ, def)
		} else {
			w.line("%s %s", name, typ)
		}
	}
	w.line("}")
}

// oneofNone is the first member of a oneof's enum: the oneof set to none
// of its fields.
const oneofNone = "none"

// fieldName takes want among a struct's fields, or the first free name made
// from it.
func fieldName(taken map[string]bool, want string, renamed func(to string)) string {
	name := want
	if parser.LookupIdent(name) != parser.IDENT {
		name += "_"
	}
	for i := 2; taken[strings.ToLower(name)]; i++ {
		name = want + strconv.Itoa(i)
	}
	taken[strings.ToLower(name)] = true
	if name != want {
		renamed(name)
	}
	return name
}

// oneof writes a payload enum for o: a member per field, carrying it, after
// one that carries nothing and is the oneof unset.
func (w *writer) oneof(o protoreflect.OneofDescriptor) {
	w.line("enum %s {", w.types[o.FullName()])
	members := map[string]bool{oneofNone: true}
	w.line("%s", oneofNone)
	for i := range o.Fields().Len() {
		f := o.Fields().Get(i)
		typ, kind, why := w.scalar(f)
		if why != "" {
			w.note("field %s of %s is left out: %s", f.Name(), o.FullName(), why)
			continue
		}
		want := f.JSONName()
		if want == "" {
			want = camel(string(f.Name()))
		}
		name := fieldName(members, want, func(to string) {
			w.note("field %s of %s is %s", f.Name(), o.FullName(), to)
		})
		w.comment(f)
		if kind != "" {
			w.line("#[grpc.field(%d, %s)]", f.Number(), kind)
		} else {
			w.line("#[grpc.field(%d)]", f.Number())
		}
		w.line("%s %s", name, typ)
	}
	w.line("}")
}

// fieldType is how a field is declared: its SNGL type, the kind its mark
// names where the type's own is not the wire's, or why it has no field.
func (w *writer) fieldType(f protoreflect.FieldDescriptor) (typ, kind, why string) {
	if f.IsMap() {
		if f.MapKey().Kind() != protoreflect.StringKind {
			return "", "", fmt.Sprintf("a map keyed by %s, where only a string key is read", f.MapKey().Kind())
		}
		v, k, why := w.scalar(f.MapValue())
		if why != "" {
			return "", "", why
		}
		return "map[string, " + v + "]", k, ""
	}
	t, k, why := w.scalar(f)
	if why != "" {
		return "", "", why
	}
	switch {
	case f.IsList():
		t = "list[" + t + "]"
	case f.HasPresence() && f.Cardinality() != protoreflect.Required:
		t = "option[" + t + "]"
	}
	return t, k, ""
}

func (w *writer) scalar(f protoreflect.FieldDescriptor) (typ, kind, why string) {
	switch f.Kind() {
	case protoreflect.BoolKind:
		return "bool", "", ""
	case protoreflect.StringKind:
		return "string", "", ""
	case protoreflect.BytesKind:
		return "string", "bytes", ""
	case protoreflect.DoubleKind:
		return "float", "", ""
	case protoreflect.FloatKind:
		return "float", "float", ""
	// A field takes the SNGL type its wire width holds on every target: a
	// signed 32-bit one fits an int, which is 32 bits on Kotlin, and a wider
	// one is sized.
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int", f.Kind().String(), ""
	case protoreflect.Uint32Kind:
		return "uint32", "", ""
	case protoreflect.Fixed32Kind:
		return "uint32", f.Kind().String(), ""
	case protoreflect.Int64Kind:
		return "int64", "", ""
	case protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64", f.Kind().String(), ""
	case protoreflect.Uint64Kind:
		return "uint64", "", ""
	case protoreflect.Fixed64Kind:
		return "uint64", f.Kind().String(), ""
	case protoreflect.EnumKind:
		return w.types[f.Enum().FullName()], "", ""
	case protoreflect.MessageKind:
		return w.types[f.Message().FullName()], "", ""
	}
	return "", "", fmt.Sprintf("a %s, which has no field", f.Kind())
}

// zero is a field's default, proto3's zero, so a literal names only what it
// sets; a required message has none.
func (w *writer) zero(f protoreflect.FieldDescriptor, typ string) string {
	switch {
	case strings.HasPrefix(typ, "option["):
		return "null"
	case f.IsList():
		return "[]"
	case f.IsMap():
		return "{}"
	}
	switch f.Kind() {
	case protoreflect.BoolKind:
		return "false"
	case protoreflect.StringKind, protoreflect.BytesKind:
		return `""`
	case protoreflect.DoubleKind, protoreflect.FloatKind:
		return "0.0"
	case protoreflect.EnumKind:
		e := f.Enum()
		return typ + "." + w.memberNames(e)[f.Default().Enum()]
	case protoreflect.MessageKind:
		return ""
	}
	return "0"
}

// memberNames are the SNGL names of an enum's values by number: each value's
// name with the enum's own as its prefix taken off, `BOOK_KIND_HARD_COVER` →
// `hardCover`. A value aliasing an earlier number has none.
func (w *writer) memberNames(e protoreflect.EnumDescriptor) map[protoreflect.EnumNumber]string {
	prefix := screaming(string(e.Name())) + "_"
	out := map[protoreflect.EnumNumber]string{}
	taken := map[string]bool{}
	for i := range e.Values().Len() {
		v := e.Values().Get(i)
		if _, alias := out[v.Number()]; alias {
			continue
		}
		raw := string(v.Name())
		if s := strings.TrimPrefix(raw, prefix); s != raw && s != "" && !unicode.IsDigit(rune(s[0])) {
			raw = s
		}
		want := camel(strings.ToLower(raw))
		name := want
		if parser.LookupIdent(name) != parser.IDENT {
			name += "_"
		}
		for i := 2; taken[name]; i++ {
			name = want + strconv.Itoa(i)
		}
		taken[name] = true
		out[v.Number()] = name
	}
	return out
}

func (w *writer) enum(e protoreflect.EnumDescriptor) {
	w.comment(e)
	w.line("enum %s {", w.types[e.FullName()])
	names := w.memberNames(e)
	for i := range e.Values().Len() {
		v := e.Values().Get(i)
		name, ok := names[v.Number()]
		if !ok || v != e.Values().ByNumber(v.Number()) {
			w.note("%s is left out: it aliases %s", v.FullName(), e.Values().ByNumber(v.Number()).Name())
			continue
		}
		w.comment(v)
		w.line("#[grpc.value(%d)]", v.Number())
		w.line("%s", name)
	}
	w.line("}")
}

// services writes a function per method, and a component over a unary one
// the file says has no side effects.
func (w *writer) services() {
	type method struct {
		m         protoreflect.MethodDescriptor
		fn, adapt string
	}
	var methods []method
	for i := range w.file.Services().Len() {
		s := w.file.Services().Get(i)
		for j := range s.Methods().Len() {
			m := s.Methods().Get(j)
			base := camel(string(m.Name()))
			base = strings.ToLower(base[:1]) + base[1:]
			md := method{m: m, fn: w.claim(base+"Call", func(to string) { w.note("%s is declared as %s: the name is taken", m.FullName(), to) })}
			if readOnly(m) && !m.IsStreamingClient() && !m.IsStreamingServer() {
				if why := keyProblem(m.Input(), map[protoreflect.FullName]bool{}); why != "" {
					w.note("%s has no component: its request %s, and a query's key is compared", m.FullName(), why)
				} else {
					md.adapt = w.claim(base, func(to string) { w.note("%s's component is %s: the name is taken", m.FullName(), to) })
				}
			}
			methods = append(methods, md)
		}
	}
	for _, md := range methods {
		m := md.m
		req, resp := w.types[m.Input().FullName()], w.types[m.Output().FullName()]
		path := quote("/" + string(m.Parent().FullName()) + "/" + string(m.Name()))
		w.line("")
		w.comment(m)
		switch {
		case m.IsStreamingClient() && m.IsStreamingServer():
			w.line("func %s(requests list[%s], each func(%s), life async.Lifetime = async.forever) async.Result[int] {", md.fn, req, resp)
			w.streamCall(req, resp, path, "requests", "each")
		case m.IsStreamingServer():
			w.line("func %s(request %s, each func(%s), life async.Lifetime = async.forever) async.Result[int] {", md.fn, req, resp)
			w.streamCall(req, resp, path, "[request]", "each")
		case m.IsStreamingClient():
			w.line("func %s(requests list[%s], life async.Lifetime = async.forever) async.Result[%s] {", md.fn, req, resp)
			w.line("var got list[%s] = []", resp)
			w.line("match var r = grpc.stream[%s, %s](server=server, method=%s, requests=requests, each=func(m %s) { got.push(m) }, descriptor=descriptor, life=life) {", req, resp, path, resp)
			w.line("failed { return {failed=grpc.classify(r)} }")
			w.line("ok {")
			w.line("if got.length() != 1 {")
			w.line(`return {failed=async.Failure{kind=async.FailureKind.server, message="a call answered {got.length()} messages, where the method answers one", code="INTERNAL"}}`)
			w.line("}")
			w.line("return {ok=got[0]}")
			w.line("}")
			w.line("}")
			w.line("}")
		default:
			w.line("func %s(request %s, life async.Lifetime = async.forever) async.Result[%s] {", md.fn, req, resp)
			w.line("match var r = grpc.call[%s, %s](server=server, method=%s, request=request, descriptor=descriptor, life=life) {", req, resp, path)
			w.line("failed { return {failed=grpc.classify(r)} }")
			w.line("ok { return {ok=r} }")
			w.line("}")
			w.line("}")
		}
	}
	for _, md := range methods {
		if md.adapt == "" {
			continue
		}
		req, resp := w.types[md.m.Input().FullName()], w.types[md.m.Output().FullName()]
		w.line("")
		w.line("// %s, asked again whenever request changes.", md.m.Name())
		w.line("component %s[F any](", md.adapt)
		w.line("request %s,", req)
		w.line(":value option[%s] = null,", resp)
		w.line(":pending bool = false,")
		w.line(":failure option[async.Failure] = null,")
		w.line("@load(value %s),", resp)
		w.line("@fail(f async.Failure),")
		w.line(") F {")
		w.line("// Asks again without a change of request: a retry.")
		w.line("func refresh() {")
		w.line("query.refresh()")
		w.line("}")
		w.line("")
		w.line("async.query #query(")
		w.line("on=request,")
		w.line("fetch=%s,", md.fn)
		w.line(":value=value,")
		w.line(":pending=pending,")
		w.line(":failure=failure,")
		w.line("@load { load() },")
		w.line("@fail { fail() },")
		w.line(")")
		w.line("}")
	}
}

// streamCall writes the body of a function over grpc.stream, answering how
// many messages came.
func (w *writer) streamCall(req, resp, path, requests, each string) {
	w.line("match var r = grpc.stream[%s, %s](server=server, method=%s, requests=%s, each=%s, descriptor=descriptor, life=life) {", req, resp, path, requests, each)
	w.line("failed { return {failed=grpc.classify(r)} }")
	w.line("ok { return {ok=r} }")
	w.line("}")
	w.line("}")
}

// readOnly reports whether the file says m has no side effects: the one
// thing a descriptor says that tells a read from a write.
func readOnly(m protoreflect.MethodDescriptor) bool {
	opts, ok := m.Options().(*descriptorpb.MethodOptions)
	return ok && opts.GetIdempotencyLevel() == descriptorpb.MethodOptions_NO_SIDE_EFFECTS
}

// keyProblem says why a message cannot be a query's key, which every target
// compares: one holding a list or a map, however deep.
func keyProblem(m protoreflect.MessageDescriptor, seen map[protoreflect.FullName]bool) string {
	if seen[m.FullName()] {
		return ""
	}
	seen[m.FullName()] = true
	for i := range m.Fields().Len() {
		f := m.Fields().Get(i)
		switch {
		case f.IsMap() && f.MapKey().Kind() != protoreflect.StringKind:
			// Left out of the struct, so nothing compares it.
		case f.IsList() || f.IsMap():
			return "holds " + string(f.Name()) + ", a list or a map"
		case f.Message() != nil:
			if why := keyProblem(f.Message(), seen); why != "" {
				return why
			}
		}
	}
	return ""
}

// camel is a proto name as a SNGL identifier: each run after an underscore
// starts upper case, `page_count` → `pageCount`; the first keeps its case.
func camel(s string) string {
	var b strings.Builder
	upper := false
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) || r > unicode.MaxASCII {
			upper = b.Len() > 0
			continue
		}
		if b.Len() == 0 && unicode.IsDigit(r) {
			b.WriteByte('n')
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	return b.String()
}

func capital(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// screaming is a CamelCase name as protobuf's style writes an enum value's
// prefix: `BookKind` → `BOOK_KIND`.
func screaming(s string) string {
	var b strings.Builder
	rs := []rune(s)
	for i, r := range rs {
		if i > 0 && unicode.IsUpper(r) && (unicode.IsLower(rs[i-1]) || i+1 < len(rs) && unicode.IsLower(rs[i+1])) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToUpper(r))
	}
	return b.String()
}

