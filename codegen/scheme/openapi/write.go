package openapi

import (
	"fmt"
	"strconv"
	"strings"

	"duckfam.us/sngl/ast"
	"duckfam.us/sngl/internal/parser"
)

// Write is the package's source for spec, read from the document named
// from: written here, then parsed and printed by the formatter, so what the
// import resolves to reads as `sngl fmt` writes it and a mistake here is a
// parse error rather than a package that says something else.
func Write(spec *Spec, from string) (string, error) {
	w := &writer{}
	w.line("// Code generated by the openapi: scheme from %s. DO NOT EDIT.", from)
	w.line("")
	w.line(`import async "sngl:async"`)
	w.line(`import http "sngl:http"`)
	w.line(`import json "sngl:json"`)
	if spec.Time {
		w.line(`import time "sngl:time"`)
	}
	w.line("")
	where := "the API"
	if spec.Title != "" {
		where = spec.Title
	}
	w.line("// Where %s is: the spec's first server. Provide another to", where)
	w.line("// point a subtree, or a test, somewhere else.")
	w.line("context #server(%s)", quote(spec.Server))
	for _, s := range spec.Schemas {
		w.line("")
		w.schema(s)
	}
	for _, op := range spec.Operations {
		if op.Query != "" {
			w.line("")
			w.queryStruct(op)
		}
	}
	w.line("")
	w.b.WriteString(answered)
	for _, op := range spec.Operations {
		w.line("")
		w.call(op)
	}
	for _, op := range spec.Operations {
		if op.Component != "" {
			w.line("")
			w.adapter(op)
		}
	}
	doc, err := parser.Parse("openapi.sngl", []byte(w.b.String()))
	if err != nil {
		return "", fmt.Errorf("openapi: the package written does not parse: %w", err)
	}
	return parser.Format(doc), nil
}

const answered = `// What a request answered, where it arrived with a 2xx status: the response,
// or the failure that kept it from arriving or that its status says.
func _answered(r async.Result[http.Response]) async.Result[http.Response] {
    match var got = r {
        failed { return {failed=got} }
        ok { return got.checked() }
    }
}
`

type writer struct{ b strings.Builder }

func (w *writer) line(format string, args ...any) {
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteByte('\n')
}

// comment writes text as line comments.
func (w *writer) comment(text string) {
	if text == "" {
		return
	}
	for l := range strings.SplitSeq(text, "\n") {
		if l = strings.TrimSpace(l); l == "" {
			w.line("//")
		} else {
			w.line("// %s", l)
		}
	}
}

func (w *writer) schema(s Schema) {
	w.comment(s.Doc)
	if s.Enum {
		w.line("enum %s {", s.Name)
		for _, m := range s.Members {
			if m.Wire != m.Name {
				w.line("#[json.identifier(%s)]", quote(m.Wire))
			}
			w.line("%s", m.Name)
		}
		w.line("}")
		return
	}
	w.line("struct %s {", s.Name)
	for _, f := range s.Fields {
		w.comment(f.Doc)
		if f.Wire != f.Name {
			w.line("#[json.identifier(%s)]", quote(f.Wire))
		}
		w.line("%s %s", f.Name, fieldType(f.Type, f.Optional))
	}
	w.line("}")
}

// queryStruct is the struct an operation's query is, where a parameter's
// name on the wire is not its SNGL name.
func (w *writer) queryStruct(op Operation) {
	w.line("// The query of %s %s.", strings.ToUpper(op.Method), op.PathText)
	w.line("struct %s {", op.Query)
	for _, p := range op.Params {
		if p.Path {
			continue
		}
		if p.Wire != p.Name {
			w.line("#[http.identifier(%s)]", quote(p.Wire))
		}
		w.line("%s %s", p.Name, fieldType(p.Type, p.Optional))
	}
	w.line("}")
}

func (w *writer) call(op Operation) {
	w.line("// %s %s", strings.ToUpper(op.Method), op.PathText)
	if op.Summary != "" {
		w.line("//")
		w.line("// %s", op.Summary)
	}
	if op.Doc != "" && op.Doc != op.Summary {
		w.line("//")
		w.comment(op.Doc)
	}
	var params []string
	for _, p := range op.Params {
		params = append(params, p.Name+" "+declared(p))
	}
	if op.Body != nil {
		params = append(params, op.BodyName+" "+spell(*op.Body))
	}
	result := spell(op.Result)
	w.line("func %s(%s) async.Result[%s] {", op.Func, strings.Join(params, ", "), result)
	args := []string{"url=" + url(op)}
	if hasQuery(op.Params) {
		args = append(args, "query="+query(op))
	}
	request := "http.get(" + strings.Join(args, ", ") + ")"
	if op.Method != "get" {
		sent := append([]string{"method=http.Method." + op.Method}, args...)
		if op.Body != nil {
			sent = append(sent, `headers={"Content-Type"="application/json"}`, "body=json.encode("+op.BodyName+")")
		}
		request = "http.send(" + strings.Join(sent, ", ") + ")"
	}
	w.line("match var r = _answered(%s) {", request)
	w.line("failed { return {failed=r} }")
	w.line("ok { return json.decode[%s](r.body) }", result)
	w.line("}")
	w.line("}")
}

// adapter is an operation's component over async.query.
func (w *writer) adapter(op Operation) {
	var names []string
	for _, p := range op.Params {
		names = append(names, p.Name)
	}
	head := "// " + strings.ToUpper(op.Method) + " " + op.PathText
	if len(names) > 0 {
		head += ", asked again whenever " + strings.Join(names, " or ") + " changes"
	}
	w.line("%s.", head)
	if op.Summary != "" {
		w.line("//")
		w.line("// %s", op.Summary)
	}
	result := spell(op.Result)
	w.line("component %s[F any](", op.Component)
	for _, p := range op.Params {
		w.line("%s %s,", p.Name, declared(p))
	}
	w.line(":value option[%s] = null,", result)
	w.line(":pending bool = false,")
	w.line(":failure option[async.Failure] = null,")
	w.line("@load(value %s),", result)
	w.line("@fail(f async.Failure),")
	w.line(") F {")
	w.line("async.query(")
	switch len(op.Params) {
	case 0:
		w.line("on=0,")
		w.line("fetch=func(k int) => %s(),", op.Func)
	case 1:
		w.line("on=%s,", op.Params[0].Name)
		w.line("fetch=%s,", op.Func)
	default:
		var on, fields, passed []string
		for _, p := range op.Params {
			on = append(on, p.Name+"="+p.Name)
			fields = append(fields, p.Name+" "+fieldType(p.Type, p.Optional))
			passed = append(passed, p.Name+"=k."+p.Name)
		}
		w.line("on={%s},", strings.Join(on, ", "))
		w.line("fetch=func(k struct { %s }) => %s(%s),", strings.Join(fields, "; "), op.Func, strings.Join(passed, ", "))
	}
	w.line(":value=value,")
	w.line(":pending=pending,")
	w.line(":failure=failure,")
	w.line("@load { load() },")
	w.line("@fail { fail() },")
	w.line(")")
	w.line("}")
}

// declared is what follows a parameter's name: its type, and its default.
func declared(p Param) string {
	switch {
	case p.Optional:
		return fieldType(p.Type, true) + " = null"
	case p.Default != nil:
		return spell(p.Type) + " = " + literal(*p.Default, p.Type)
	}
	return spell(p.Type)
}

// url is the request's URL: the server, and the path with each parameter
// filled in, a string one escaped so it stays one segment.
func url(op Operation) string {
	var b strings.Builder
	b.WriteString(`"{server}`)
	for _, s := range op.Path {
		switch {
		case s.Param == "":
			b.WriteString(ast.EscapeString(s.Text, ast.StyleDouble))
		case s.Kind == KindText:
			b.WriteString("{http.pathEscape(" + s.Param + ")}")
		default:
			b.WriteString("{" + s.Param + "}")
		}
	}
	b.WriteByte('"')
	return b.String()
}

// query is the query as a struct of its parameters.
func query(op Operation) string {
	var fields []string
	for _, p := range op.Params {
		if !p.Path {
			fields = append(fields, p.Name+"="+p.Name)
		}
	}
	return op.Query + "{" + strings.Join(fields, ", ") + "}"
}

func fieldType(t Type, optional bool) string {
	if optional {
		return "option[" + spell(t) + "]"
	}
	return spell(t)
}

// spell is the type t is, as the package spells it.
func spell(t Type) string {
	switch t.Kind {
	case KindText:
		return "string"
	case KindInteger:
		return "int"
	case KindNumber:
		return "float"
	case KindBoolean:
		return "bool"
	case KindDate:
		return "time.date"
	case KindDatetime:
		return "time.datetime"
	case KindNamed:
		return t.Name
	case KindList:
		return "list[" + spell(t.Elems[0]) + "]"
	case KindDict:
		return "map[" + spell(t.Elems[0]) + ", " + spell(t.Elems[1]) + "]"
	}
	panic("openapi: no spelling for kind " + string(t.Kind))
}

// literal is a default as a literal of its type.
func literal(v string, t Type) string {
	switch t.Kind {
	case KindText:
		return quote(v)
	case KindNumber:
		if !strings.ContainsAny(v, ".eE") {
			return v + ".0"
		}
	case KindBoolean:
		if b, err := strconv.ParseBool(v); err == nil {
			return strconv.FormatBool(b)
		}
	}
	return v
}

func quote(s string) string { return `"` + ast.EscapeString(s, ast.StyleDouble) + `"` }
