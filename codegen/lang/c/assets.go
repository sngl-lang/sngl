package c

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"duckfam.us/sngl/codegen"
)

// Assets is a C file carrying the `file:` assets the build copied in the
// program, for a platform whose runtime shows them: an array of typ, which
// header declares as a name, its bytes and their length, named table, each
// entry by the path the build gave the asset -- which an image's URL names
// -- and ending at a NULL name.
func Assets(assets []codegen.FileAsset, header, typ, table string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "/* Code generated by sngl. DO NOT EDIT. */\n#include %q\n", header)
	var rows []string
	for i, fa := range assets {
		data := fa.Data
		if data == nil {
			d, err := os.ReadFile(fa.SrcPath)
			if err != nil {
				return nil, err
			}
			data = d
		}
		fmt.Fprintf(&b, "\nstatic const unsigned char sngl_asset%d[] = {", i)
		for j, c := range data {
			if j%16 == 0 {
				b.WriteString("\n\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%02x,", c)
		}
		b.WriteString("\n};\n")
		rows = append(rows, fmt.Sprintf("\t{%s, sngl_asset%d, %d},\n", strconv.Quote(filepath.ToSlash(fa.OutPath)), i, len(data)))
	}
	b.WriteString("\nconst " + typ + " " + table + "[] = {\n" + strings.Join(rows, "") + "\t{NULL, NULL, 0},\n};\n")
	return []byte(b.String()), nil
}
