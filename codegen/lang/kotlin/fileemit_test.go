package kotlin_test

import (
	"strings"
	"testing"

	"duckfam.us/sngl/codegen"
	"duckfam.us/sngl/codegen/lang/kotlin"
)

// The emitter writes one import line per required name, in the order they
// were required, between the package clause and the body; and hands back how
// the body spells each.
func TestFileEmitter_Imports(t *testing.T) {
	sink := codegen.NewMemSink()
	e := (&kotlin.Translator{}).NewFileEmitter(sink, codegen.FileOptions{
		Name:        "Main.kt",
		Source:      "app.sngl",
		Platform:    "test",
		PackageName: "a.b",
	})
	for path, want := range map[string]string{
		"android.os.Bundle":                   "Bundle",
		"x.y.MainScreen as DocScreen":         "DocScreen",
		"androidx.compose.runtime.Composable": "Composable",
	} {
		if got := e.RequireImport(path); got != want {
			t.Errorf("RequireImport(%q) = %q, want %q", path, got, want)
		}
	}
	e.RequireImport("android.os.Bundle")
	e.Write([]byte("class C\n"))
	if err := e.Close(); err != nil {
		t.Fatal(err)
	}
	got := string(sink.Files()["Main.kt"])
	const head = "// Code generated by sngl (test) from app.sngl; DO NOT EDIT.\n\npackage a.b\n\n"
	if !strings.HasPrefix(got, head) {
		t.Fatalf("header:\n%s", got)
	}
	for _, imp := range []string{"android.os.Bundle", "x.y.MainScreen as DocScreen", "androidx.compose.runtime.Composable"} {
		if n := strings.Count(got, "\nimport "+imp+"\n"); n != 1 {
			t.Errorf("import %s appears %d times:\n%s", imp, n, got)
		}
	}
	if !strings.HasSuffix(got, "\n\nclass C\n") {
		t.Errorf("body not after a blank line:\n%s", got)
	}
}

// A file that requires nothing has no import block.
func TestFileEmitter_NoImports(t *testing.T) {
	sink := codegen.NewMemSink()
	e := (&kotlin.Translator{}).NewFileEmitter(sink, codegen.FileOptions{Name: "A.kt", PackageName: "a"})
	e.Write([]byte("class A\n"))
	if err := e.Close(); err != nil {
		t.Fatal(err)
	}
	if got, want := string(sink.Files()["A.kt"]), "package a\n\nclass A\n"; got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}
