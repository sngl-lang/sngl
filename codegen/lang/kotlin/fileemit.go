package kotlin

import (
	"bytes"
	"fmt"
	"io"
	"strings"

	"duckfam.us/sngl/codegen"
	"duckfam.us/sngl/ir"
)

// fileEmitter implements codegen.FileEmitter for Kotlin output.
//
// Close assembles the generated-by header, the package clause, one import
// line per name the file required, and the body. Imports go through the same
// ktImportSet a KtIRContext keeps, so a name another import already claims is
// refused or aliased the way the translator's own are. Kotlin has no
// gofmt-equivalent in the build path, so the body is written verbatim.
// Source-map support remains deferred per Plan A non-goal.
type fileEmitter struct {
	sink    codegen.Sink
	opts    codegen.FileOptions
	buf     bytes.Buffer
	imports *ktImportSet
	closed  bool
}

func newFileEmitter(sink codegen.Sink, opts codegen.FileOptions) *fileEmitter {
	return &fileEmitter{sink: sink, opts: opts, imports: newKtImportSet()}
}

func (fe *fileEmitter) Write(p []byte) (int, error) {
	if fe.closed {
		return 0, io.ErrClosedPipe
	}
	return fe.buf.Write(p)
}

// EvalExpr / EvalStmt are placeholders until the Kotlin path is rewritten
// to emit through this surface. Today's android-kotlin path renders the body
// through its own KtIRContext and hands the imports that recorded to
// RequireImport.
func (fe *fileEmitter) EvalExpr(e ir.Expr) string   { return "" }
func (fe *fileEmitter) EvalStmt(s ir.Stmt) []string { return nil }

// RequireImport registers an import -- a fully-qualified name, or one
// written `fqn as Alias` -- and returns what the file's code spells it as.
func (fe *fileEmitter) RequireImport(path string) string {
	fe.imports.require(path)
	if _, alias, ok := strings.Cut(path, " as "); ok {
		return alias
	}
	return simpleName(path)
}

func (fe *fileEmitter) Close() error {
	if fe.closed {
		return nil
	}
	fe.closed = true

	w, err := fe.sink.Create(fe.opts.Name)
	if err != nil {
		return err
	}
	if fe.opts.Source != "" && fe.opts.Platform != "" {
		fmt.Fprintf(w, "// Code generated by sngl (%s) from %s; DO NOT EDIT.\n\n",
			fe.opts.Platform, fe.opts.Source)
	}
	if fe.opts.PackageName != "" {
		fmt.Fprintf(w, "package %s\n\n", fe.opts.PackageName)
	}
	if len(fe.imports.order) > 0 {
		for _, imp := range fe.imports.order {
			fmt.Fprintf(w, "import %s\n", imp)
		}
		io.WriteString(w, "\n")
	}
	if _, err := fe.buf.WriteTo(w); err != nil {
		w.Close()
		return err
	}
	return w.Close()
}
