// A closure crosses to C as a function C can call and the `void *` it hands
// back, which is how GLib's signals and qsort_r take one. Go's function is
// a dispatcher cgo exports, one per callback type, which finds the closure
// through cbind's registry by the index the context holds. The dispatchers sit in a file of their own,
// because a file exporting to C may define nothing in its preamble that
// another compilation unit links, and the platform's files may.

// callbacksFile is the file holding a program's dispatchers.
const callbacksFile = "sngl_callbacks.go"

// callbackName is the dispatcher cgo exports for a callback of type sig,
// named for what it takes and answers: `snglCallback_int__int` for a
// `func(int) int`. Pointer types are named for the C type they are.
func callbackName(sig *ir.FuncSig) string {
	var params []string
	for _, p := range sig.Params {
		params = append(params, callbackToken(p.Type))
	}
	if len(params) == 0 {
		params = []string{"void"}
	}
	ret := "void"
	if r := sig.Return; r != nil && r.Kind != ir.TypeVoid {
		ret = callbackToken(r)
	}
	return "snglCallback_" + strings.Join(params, "_") + "__" + ret
}

// cClosureType is the Go type of a closure taking and answering sig, each C
// type as C spells it.
func cClosureType(sig *ir.FuncSig) string {
	spell := func(t *ir.Type) string {
		if ct := ir.CTypeOf(t); ct != nil {
			return CTypeToGo(ct)
		}
		return IRTypeToGo(t)
	}
	var ps []string
	for _, p := range sig.Params {
		ps = append(ps, spell(p.Type))
	}
	out := "func(" + strings.Join(ps, ", ") + ")"
	if r := sig.Return; r != nil && r.Kind != ir.TypeVoid {
		out += " " + spell(r)
	}
	return out
}

// callbackToken is t's part of a dispatcher's name. A bool crosses as C's
// int and is named for itself, since its dispatcher differs: it asserts a
// closure taking a bool, which one taking an int is not.
func callbackToken(t *ir.Type) string {
	if ct := ir.CTypeOf(t); ct != nil {
		return strings.ReplaceAll(ct.Name, " ", "_") + strings.Repeat("_p", ct.Ptr)
	}
	if t.Kind == ir.TypeBool {
		return "bool"
	}
	return callbackCType(t).Name
}

// exportedCType is the C type cgo's _cgo_export.h declares a dispatcher's
// parameter or result as, which drops a const the Go side cannot spell:
// the preamble's extern must match it.
func exportedCType(t *ir.Type) string {
	ct := *callbackCType(t)
	ct.Const = false
	return ct.String()
}

// callbackCType is the C type a callback's parameter or result crosses as:
// a bool is C's `int`, as c.cbool makes one.
func callbackCType(t *ir.Type) *ir.CType {
	if ct := ir.CTypeOf(t); ct != nil {
		return ct
	}
	switch t.Kind {
	case ir.TypeFloat:
		return &ir.CType{Name: "double"}
	}
	return &ir.CType{Name: "int"}
}

// CallbacksSource is the Go file exporting a dispatcher for each of sigs, in
// package pkgName, its preamble including what links does so a pointer
// type's C name resolves, and the registry a closure or a value C holds
// (sngl:x/c's held) is found through. Nil where there is no callback and,
// held false, no held value. cSpelled says the
// closure a C type crosses into takes it as C spells it: in a wrapper package
// (sngl tool cgogen), whose own type for it is an alias of that and which
// cannot name itself, and in a program calling C directly, which spells every
// C type as cgo does.
func CallbacksSource(pkgName string, links []*ir.CLink, sigs []*ir.FuncSig, held, cSpelled bool) []byte {
	byName := map[string]*ir.FuncSig{}
	for _, s := range sigs {
		byName[callbackName(s)] = s
	}
	if len(byName) == 0 && !held {
		return nil
	}
	names := make([]string, 0, len(byName))
	for n := range byName {
		names = append(names, n)
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("// Code generated by sngl; DO NOT EDIT.\n\npackage " + pkgName + "\n\n/*\n")
	b.WriteString(CPreambleLines(links))
	b.WriteString("#include <stdint.h>\n\n")
	for _, n := range names {
		sig := byName[n]
		var params []string
		for _, p := range sig.Params {
			params = append(params, exportedCType(p.Type))
		}
		params = append(params, "void *")
		ret := "void"
		if r := sig.Return; r != nil && r.Kind != ir.TypeVoid {
			ret = exportedCType(r)
		}
		fmt.Fprintf(&b, "extern %s %s(%s);\n", ret, n, strings.Join(params, ", "))
	}
	b.WriteString("extern void snglRelease(void *);\n")
	b.WriteString("\nstatic void *sngl_context(uintptr_t i) { return (void *)i; }\n*/\nimport \"C\"\n\n")
	b.WriteString(`import (
	"unsafe"

	"duckfam.us/sngl/pkg/go/cbind"
)

// snglContextBase is where contexts start: past NULL, and past the page
// below which Go takes a pointer on its stack for a bad one and throws as it
// copies the stack (runtime: bad pointer in frame), which a program's
// thousandth callback reached. Go maps none of its heap this low.
const snglContextBase = 1 << 16

// snglContext registers fn and is the context C hands back to the callback
// calling it: the registry's index, offset by snglContextBase.
func snglContext(fn any) unsafe.Pointer {
	return C.sngl_context(C.uintptr_t(cbind.Register(fn) + snglContextBase))
}

func snglClosure(ctx unsafe.Pointer) any {
	return cbind.Lookup(int(uintptr(ctx)) - snglContextBase)
}

// snglRelease is what C calls with a context once it is done with the
// callback, where the function takes a #[c.release]: GLib's
// GClosureNotify, which hands the GClosure after it, and GDestroyNotify.
// A value C holds is registered as a closure is, and let go the same way.
//
//export snglRelease
func snglRelease(ctx unsafe.Pointer) { cbind.Release(int(uintptr(ctx)) - snglContextBase) }

// snglReleasePtr is snglRelease as the function pointer C calls.
func snglReleasePtr() *[0]byte { return (*[0]byte)(C.snglRelease) }
`)
	for _, n := range names {
		sig := byName[n]
		var params, args []string
		for i, p := range sig.Params {
			a := fmt.Sprintf("a%d", i)
			params = append(params, a+" "+CTypeToGo(callbackCType(p.Type)))
			switch {
			case ir.CTypeOf(p.Type) != nil:
				args = append(args, a)
			case p.Type.Kind == ir.TypeBool:
				args = append(args, a+" != 0")
			default:
				args = append(args, IRTypeToGo(p.Type)+"("+a+")")
			}
		}
		params = append(params, "ctx unsafe.Pointer")
		// A closure released already answers C's zero: a callback C calls
		// after it let the context go finds nothing, as cbind.Dispatch does.
		closure := IRTypeToGo(ir.FuncOf(sig.Params, sig.Return))
		if cSpelled {
			closure = cClosureType(sig)
		}
		lookup := "fn, ok := snglClosure(ctx).(" + closure + ")"
		call := "fn(" + strings.Join(args, ", ") + ")"
		ret, body := "", lookup+"\n\tif ok {\n\t\t"+call+"\n\t}"
		if r := sig.Return; r != nil && r.Kind != ir.TypeVoid {
			ct := CTypeToGo(callbackCType(r))
			ret = " " + ct
			set := "r = " + call
			switch {
			case r.Kind == ir.TypeBool && ir.CTypeOf(r) == nil:
				set = "if " + call + " {\n\t\t\tr = 1\n\t\t}"
			case ir.CTypeOf(r) == nil:
				set = "r = " + ct + "(" + call + ")"
			}
			body = lookup + "\n\tvar r " + ct + "\n\tif ok {\n\t\t" + set + "\n\t}\n\treturn r"
		}
		fmt.Fprintf(&b, "\n//export %s\nfunc %s(%s)%s {\n\t%s\n}\n", n, n, strings.Join(params, ", "), ret, body)
		fmt.Fprintf(&b, "\n// %sPtr is %s as the function pointer C calls.\nfunc %sPtr() *[0]byte { return (*[0]byte)(C.%s) }\n", n, n, n, n)
	}
	return []byte(b.String())
}

// generatedPackage is the package the platform's Go files declare, which
// the language's own files must declare too.
func generatedPackage(generated map[string][]byte) (string, error) {
	names := make([]string, 0, len(generated))
	for n := range generated {
		if strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") && !strings.Contains(n, "/") {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	for _, n := range names {
		f, err := parser.ParseFile(token.NewFileSet(), n, generated[n], parser.PackageClauseOnly)
		if err == nil {
			return f.Name.Name, nil
		}
	}
	return "", fmt.Errorf("a C function takes a callback, and no Go file the platform generated names the package its dispatchers join")
}
