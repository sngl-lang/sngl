package win32

import "strings"

// shimFile is the Go file holding the runtime calls a Go program's entry, its
// test agent, its posting and its carried files make, each a function of the
// program's own: the entry and the hooks are written once, and the language's
// `cgo` option decides what the functions call. win32.sngl's reservedNames
// holds each name, so no program's declaration takes one.
const shimFile = "sngl_rt.go"

// shimWrapper is shimFile where Go calls the wrappers (`cgo=wrapper`): each
// function hands its call on.
const shimWrapper = `// Code generated by sngl (win32). DO NOT EDIT.

package main

import "duckfam.us/sngl/lib/platform/win32/cgo"

func snglWin32Hold()                                 { cgo.SnglWin32Hold() }
func snglWin32Present()                              { cgo.SnglWin32Present() }
func snglWin32Run()                                  { cgo.SnglWin32Run() }
func snglWin32Step()                                 { cgo.SnglWin32Step() }
func snglWin32Snapshot(path string, w, h int) int    { return cgo.SnglWin32Snapshot(path, w, h) }
func snglWin32CarryFile(name, data string, n int)    { cgo.SnglWin32CarryFile(name, data, n) }
func snglPost(fn func())                             { cgo.SnglPost(fn) }
`

// shimDirect is shimFile where the program calls C itself (`cgo=direct`): a
// closure crosses as a context its own trampoline looks up, so the file needs
// none of the dispatchers a program's callbacks get.
const shimDirect = `// Code generated by sngl (win32). DO NOT EDIT.

package main

/*
#include "sngl_win32.h"
#include <stdint.h>
#include <stdlib.h>

extern void snglShimCall(void *);
extern void snglShimRelease(void *);

static void *sngl_shim_context(uintptr_t i) { return (void *)i; }
*/
import "C"

import (
	"unsafe"

	"duckfam.us/sngl/pkg/go/cbind"
)

// snglShimBase keeps a context off NULL and the low page, as a program's
// callbacks' snglContextBase does.
const snglShimBase = 1 << 16

func snglShimContext(fn func()) unsafe.Pointer {
	return C.sngl_shim_context(C.uintptr_t(cbind.Register(fn) + snglShimBase))
}

//export snglShimCall
func snglShimCall(ctx unsafe.Pointer) {
	if fn, ok := cbind.Lookup(int(uintptr(ctx)) - snglShimBase).(func()); ok {
		fn()
	}
}

//export snglShimRelease
func snglShimRelease(ctx unsafe.Pointer) { cbind.Release(int(uintptr(ctx)) - snglShimBase) }

func snglPost(fn func()) {
	C.sngl_post((*[0]byte)(C.snglShimCall), snglShimContext(fn), (*[0]byte)(C.snglShimRelease))
}

func snglWin32Hold()    { C.sngl_win32_hold() }
func snglWin32Present() { C.sngl_win32_present() }
func snglWin32Run()     { C.sngl_win32_run() }
func snglWin32Step()    { C.sngl_win32_step() }

func snglWin32Snapshot(path string, w, h int) int {
	p := C.CString(path)
	defer C.free(unsafe.Pointer(p))
	return int(C.sngl_win32_snapshot(p, C.int(w), C.int(h)))
}

func snglWin32CarryFile(name, data string, n int) {
	cn, cd := C.CString(name), C.CString(data)
	defer C.free(unsafe.Pointer(cn))
	defer C.free(unsafe.Pointer(cd))
	C.sngl_win32_carry_file(cn, cd, C.int(n))
}
`

// shim is shimFile's text for a program that calls C directly or not.
func shim(direct bool) string {
	if direct {
		return shimDirect
	}
	return strings.TrimSpace(shimWrapper) + "\n"
}
