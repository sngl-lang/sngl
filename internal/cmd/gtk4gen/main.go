// Command gtk4gen writes lib/platform/gtk4next/widgets.sngl, sngl:platform/gtk4's
// widget declarations, from the GIR the gtk4 platform bundles. It runs from
// lib's go:generate, before cgogen wraps what it wrote.
package main

import (
	"flag"
	"log"
	"os"

	"duckfam.us/sngl/codegen/platform/gtk4"
)

const header = "// Code generated by gtk4gen from the bundled Gtk-4.0.gir; DO NOT EDIT.\n"

func main() {
	out := flag.String("out", "platform/gtk4next/widgets.sngl", "the file to write")
	flag.Parse()
	src, err := gtk4.WidgetSource(header)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
