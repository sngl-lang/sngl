// Command specgen generates docs/reference/specification.md from the v2 EBNF grammar.
//
// Usage: go run ./internal/cmd/specgen
package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

func main() {
	_, thisFile, _, _ := runtime.Caller(0)
	root := filepath.Join(filepath.Dir(thisFile), "..", "..", "..")
	ebnfPath := filepath.Join(root, "internal", "parser", "sngl.ebnf")
	outPath := filepath.Join(root, "docs", "reference", "specification.md")

	prods := parseEBNF(ebnfPath)

	var b strings.Builder
	b.WriteString(`---
title: "Language Specification"
order: 50
description: "Formal grammar and semantics of the SNGL language"
---

<!-- Code generated by internal/cmd/specgen from internal/parser/sngl.ebnf; DO NOT EDIT. -->

`)

	writeGrammar(&b, prods)
	writePrecedence(&b)
	writeKeywords(&b)
	writeSemantics(&b)

	os.WriteFile(outPath, []byte(b.String()), 0o644)
}

// production is a named EBNF rule with its body and preceding comment block.
type production struct {
	name    string
	body    string
	comment string // preceding # comment lines
}

var prodRE = regexp.MustCompile(`^(\w+)\s*=\s*(.*)`)

// parseEBNF reads the EBNF file and extracts productions with their comments.
func parseEBNF(path string) []production {
	f, err := os.Open(path)
	if err != nil {
		fatalf("open %s: %v", path, err)
	}
	defer f.Close()

	var prods []production
	var commentBuf []string
	var nameBuf string
	var bodyBuf []string

	flush := func() {
		if nameBuf != "" {
			prods = append(prods, production{
				name:    nameBuf,
				body:    strings.Join(bodyBuf, "\n"),
				comment: strings.Join(commentBuf, "\n"),
			})
		}
		nameBuf = ""
		bodyBuf = nil
	}

	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := scanner.Text()

		// Comment line
		if strings.HasPrefix(line, "#") {
			if nameBuf != "" {
				flush()
				commentBuf = nil
			}
			commentBuf = append(commentBuf, line)
			continue
		}

		// Blank line
		if strings.TrimSpace(line) == "" {
			if nameBuf != "" {
				flush()
			}
			continue
		}

		// Check if this line starts a new production (Name = ...)
		if m := prodRE.FindStringSubmatch(line); m != nil {
			// If we were already in a production, flush it
			if nameBuf != "" {
				flush()
				commentBuf = nil
			}
			nameBuf = m[1]
			bodyBuf = []string{m[2]}
			continue
		}

		// Continuation of current production body
		if nameBuf != "" {
			bodyBuf = append(bodyBuf, line)
		} else {
			// Not in a production, not a comment — skip
			commentBuf = nil
		}
	}

	flush()
	return prods
}

