var tokenRE = regexp.MustCompile(`\b[a-z][a-z_]*\b`)

func writeGrammar(b *strings.Builder, prods []production) {
	b.WriteString("## Grammar\n\n")
	b.WriteString("SNGL uses an LL(1) recursive-descent parser with automatic semicolon insertion.\n")
	b.WriteString("The following grammar is extracted from the v2 EBNF definition.\n\n")
	b.WriteString("**Notation:** `{ X }` = zero or more, `[ X ]` = optional, `|` = alternative, `( X )` = grouping.\n\n")

	// Build map from name to production
	prodMap := map[string]production{}
	for _, p := range prods {
		prodMap[p.name] = p
	}

	for _, sec := range sections {
		b.WriteString("### " + sec.title + "\n\n```ebnf\n")
		for _, name := range sec.rules {
			p, ok := prodMap[name]
			if !ok {
				continue
			}
			body := formatBody(p.body)
			fmt.Fprintf(b, "%s = %s\n\n", name, body)
		}
		b.WriteString("```\n\n")
	}
}

// formatBody replaces terminal names with readable tokens and cleans up the body.
func formatBody(body string) string {
	// Strip trailing " ."
	body = strings.TrimSuffix(strings.TrimSpace(body), ".")
	body = strings.TrimSpace(body)

	// Replace terminal names with readable symbols
	body = tokenRE.ReplaceAllStringFunc(body, func(s string) string {
		if r, ok := tokenReplacements[s]; ok {
			return r
		}
		return s
	})

	// Clean up multi-line bodies: normalize indentation
	lines := strings.Split(body, "\n")
	if len(lines) == 1 {
		return strings.TrimSpace(lines[0])
	}

	var out []string
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		// Preserve leading pipe for alternatives
		if strings.HasPrefix(trimmed, "|") {
			out = append(out, "    "+trimmed)
		} else {
			out = append(out, "    "+trimmed)
		}
	}
	return "\n" + strings.Join(out, "\n")
}

func writePrecedence(b *strings.Builder) {
	b.WriteString("## Operator Precedence\n\n")
	b.WriteString("| Precedence | Operators | Associativity | Description |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	b.WriteString("| 1 | `? :` | right | Ternary |\n")
	b.WriteString("| 2 | `\\|\\|` | left | Logical OR |\n")
	b.WriteString("| 3 | `&&` | left | Logical AND |\n")
	b.WriteString("| 4 | `==`, `!=` | left | Equality |\n")
	b.WriteString("| 5 | `<`, `>`, `<=`, `>=` | left | Comparison |\n")
	b.WriteString("| 6 | `+`, `-` | left | Addition |\n")
	b.WriteString("| 7 | `*`, `/`, `%` | left | Multiplication |\n")
	b.WriteString("| 8 | `!`, `-` (unary) | right | Unary |\n")
	b.WriteString("| 9 | `.`, `[]`, `()` | left | Postfix |\n\n")
}

