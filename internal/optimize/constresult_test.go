// purepkgImport resolves the purepkg test package through the real go://
// importer, once. The declared types the results document is checked against
// come from there, so a fixture written against a hand-built *ir.Type would
// only be asserting itself.
var purepkgImport = sync.OnceValues(func() (*ir.NativeImport, error) {
	return (&golang.GoImporter{}).Resolve("go://"+purepkgPath, projectDir())
})

// importedFunc returns the imported declaration of a purepkg function.
func importedFunc(t *testing.T, name string) *ir.Func {
	t.Helper()
	ni, err := purepkgImport()
	if err != nil {
		t.Skipf("resolving %s: %v", purepkgPath, err)
	}
	for _, f := range ni.Funcs {
		if f.Name == name {
			return f
		}
	}
	t.Fatalf("purepkg declares no %s", name)
	return nil
}

// checkResults runs one `const k = <expr>` line through the results reader
// against the return type of the named purepkg function.
func checkResults(t *testing.T, fn, expr string) ir.Expr {
	t.Helper()
	f := importedFunc(t, fn)
	got, err := parseConstResults("results.sngl", []byte("const k = "+expr+"\n"), map[string]*ir.Type{"k": f.Return})
	if err != nil {
		t.Fatalf("parseConstResults(%s): %v", expr, err)
	}
	return got["k"]
}

// The results document is the contract between pkg/go/consteval and the
// folder: what that encoder writes, this reads back — as IR checked against
// the declared type of the function that produced it.
func TestParseConstResultsScalars(t *testing.T) {
	f := importedFunc(t, "Greet")
	src := []byte(`// Code generated by pkg/go/consteval. DO NOT EDIT.

const s = "a\"b\\c\nd\{e\}"
`)
	got, err := parseConstResults("results.sngl", src, map[string]*ir.Type{"s": f.Return})
	if err != nil {
		t.Fatal(err)
	}
	lit, ok := got["s"].(*ir.Literal)
	if !ok {
		t.Fatalf("s = %T", got["s"])
	}
	// Raw holds the unquoted content: the escapes the encoder added are gone.
	if lit.Raw != "a\"b\\c\nd{e}" {
		t.Errorf("s = %q", lit.Raw)
	}
	if lit.Type == nil || lit.Type.Kind != ir.TypeString {
		t.Errorf("s typed %v, want string", lit.Type)
	}
}

// A float whose value is a whole number stays a float. The JSON results path
// had only float64 to work with and turned every whole one into an int, so a
// function declared to return a float folded to an int literal.
func TestWholeFloatStaysFloat(t *testing.T) {
	lit, ok := checkResults(t, "Whole", "3").(*ir.Literal)
	if !ok {
		t.Fatalf("got %T", checkResults(t, "Whole", "3"))
	}
	if lit.Type == nil || lit.Type.Kind != ir.TypeFloat {
		t.Errorf("Whole() folded to %v, want float", lit.Type)
	}
}

// A duration keeps its unit. The value model held only the magnitude, so the
// literal reached codegen as a bare int.
func TestDurationKeepsItsUnit(t *testing.T) {
	// The Go importer models time.Duration by its underlying int64, so the
	// declared type is int and the unit can only come from the value itself.
	lit, ok := checkResults(t, "Wait", "250ms").(*ir.Literal)
	if !ok {
		t.Fatalf("got %T", checkResults(t, "Wait", "250ms"))
	}
	if lit.Suffix != "ms" {
		t.Errorf("Wait() folded to suffix %q, want ms", lit.Suffix)
	}
	if lit.Type == nil || lit.Type.Kind != ir.TypeUnit {
		t.Errorf("Wait() typed %v, want a unit type", lit.Type)
	}
}

// Field names come off the imported declaration, which is where the scheme
// importer recorded the Go name it derived each SNGL name from. Nothing here
// re-derives the mapping, so `HTTPStatus` lands on whatever the importer
// decided rather than on a second guess at the same rule.
func TestStructFieldNamesComeFromTheImport(t *testing.T) {
	lit, ok := checkResults(t, "GetMeta", `Meta{URL = "/a", ID = 7, HTTPStatus = 404}`).(*ir.StructLit)
	if !ok {
		t.Fatalf("got %T", checkResults(t, "GetMeta", `Meta{URL = "/a", ID = 7, HTTPStatus = 404}`))
	}
	if lit.Def == nil || lit.Def.Name != "Meta" {
		t.Fatalf("GetMeta() folded to a literal with Def %v, want Meta", lit.Def)
	}
	// The names the importer derived, in the order it declared them. The
	// value model held a map, so the order was alphabetical and the names
	// were a second, independent guess at the importer's rule.
	var got []string
	for _, f := range lit.Fields {
		got = append(got, f.Name)
	}
	want := []string{"url", "id", "hTTPStatus"}
	if len(got) != len(want) {
		t.Fatalf("fields %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("fields %v, want %v (the declaration's names, in its order: %v)", got, want, fieldNames(lit.Def))
		}
	}
}

func fieldNames(sd *ir.StructDef) []string {
	var out []string
	for _, f := range sd.Fields {
		out = append(out, f.Name)
	}
	return out
}

// A struct nested inside a list inside a struct keeps its own declaration at
// every level, because every level was checked against the declared type.
func TestNestedStructKeepsItsDef(t *testing.T) {
	list, ok := checkResults(t, "GetGroups", `[Group{Label = "first", Items = [Item{Name = "alpha", Value = 1}]}]`).(*ir.ListLit)
	if !ok {
		t.Fatalf("got %T", checkResults(t, "GetGroups", `[Group{Label = "first", Items = []}]`))
	}
	group, ok := list.Elems[0].(*ir.StructLit)
	if !ok || group.Def == nil || group.Def.Name != "Group" {
		t.Fatalf("element is %T with Def %v, want a Group", list.Elems[0], group)
	}
	var items *ir.ListLit
	for _, f := range group.Fields {
		if f.Name == "items" {
			items, _ = f.Value.(*ir.ListLit)
		}
	}
	if items == nil {
		t.Fatalf("group has no items list: %v", fieldNames(group.Def))
	}
	item, ok := items.Elems[0].(*ir.StructLit)
	if !ok || item.Def == nil || item.Def.Name != "Item" {
		t.Fatalf("nested element is %T with Def %v, want an Item", items.Elems[0], item)
	}
}

// A value the encoder could not have written is a corrupt document, not an
// empty value.
func TestParseConstResultsRejectsNonValue(t *testing.T) {
	f := importedFunc(t, "Greet")
	_, err := parseConstResults("results.sngl", []byte("const x = someFunc()\n"), map[string]*ir.Type{"x": f.Return})
	if err == nil {
		t.Fatal("a non-literal initializer was accepted")
	}
}

// The encoder writes the Go type name, so a value of the wrong type is caught
// here rather than folded into a literal shaped like the expected one. Tally
// has Item's fields, so nothing but the name distinguishes them — the check
// that the encoder and the importer read the same Go type.
func TestParseConstResultsRejectsWrongStruct(t *testing.T) {
	f := importedFunc(t, "GetTally")
	_, err := parseConstResults("results.sngl", []byte(`const x = Item{Name = "a", Value = 1}`+"\n"), map[string]*ir.Type{"x": f.Return})
	if err == nil {
		t.Fatal("an Item was accepted where a Tally was expected")
	}
	if !strings.Contains(err.Error(), "Tally") {
		t.Errorf("error does not name the expected type: %v", err)
	}
}
