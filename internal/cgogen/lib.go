// Plan is what a run writes: the wrapper package's files, by name, in Dir,
// and each .sngl file of the wrapped packages as it is with its marks.
type Plan struct {
	Dir     string
	Files   map[string][]byte
	Sources map[string][]byte
	// Stale are files in Dir a run before wrote and this one does not.
	Stale []string
}

// header starts every file the tool writes, which is how a later run tells
// its own stale files from the files around them.
const header = "// Code generated by sngl tool cgogen; DO NOT EDIT."

// Lib plans the wrapper package of `sngl:<name>` and of the packages under
// it that it imports (sngl:platform/win32 and sngl:platform/win32/api), in a
// checkout of this repository rooted at root. dir is where the wrapper
// package goes, empty for `<name>/cgo` beside the package, and its import
// path is read from the nearest go.mod.
func Lib(root, name, dir, goos string) (*Plan, error) {
	pkg, diags := checker.CheckLibPackage(name)
	if pkg == nil {
		return nil, fmt.Errorf("no package sngl:%s", name)
	}
	if len(diags) > 0 {
		return nil, fmt.Errorf("sngl:%s does not check: %v", name, diags[0])
	}
	// Both absolute, so the path from dir to each package's sources is one
	// filepath.Rel can make whichever was given relative.
	root, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	pkgDir := func(p *ir.Package) string {
		return filepath.Join(root, "lib", filepath.FromSlash(strings.TrimPrefix(p.Path, "sngl:")))
	}
	if dir == "" {
		dir = filepath.Join(pkgDir(pkg), "cgo")
	}
	if dir, err = filepath.Abs(dir); err != nil {
		return nil, err
	}
	importPath, err := goImportPath(dir)
	if err != nil {
		return nil, err
	}
	pkgs := []*ir.Package{pkg}
	for _, imp := range pkg.Imports {
		if imp.Pkg != nil && strings.HasPrefix(imp.Pkg.Path, pkg.Path+"/") && !slices.Contains(pkgs, imp.Pkg) {
			pkgs = append(pkgs, imp.Pkg)
		}
	}
	sources := map[*ir.Package]string{}
	for _, p := range pkgs {
		rel, err := filepath.Rel(dir, pkgDir(p))
		if err != nil {
			return nil, err
		}
		sources[p] = filepath.ToSlash(rel)
	}
	res, err := Generate(Options{Pkgs: pkgs, ImportPath: importPath, GOOS: goos, Sources: sources})
	if err != nil {
		return nil, err
	}
	plan := &Plan{Dir: dir, Files: res.Files, Sources: map[string][]byte{}}
	// Every file of each package is rewritten, one with no mark now
	// included, so a mark nothing wraps any longer is taken out.
	byFile := map[string][]Mark{}
	for _, m := range res.Marks {
		byFile[m.Pos.File] = append(byFile[m.Pos.File], m)
	}
	for _, p := range pkgs {
		files, err := fs.Glob(lib.FS, strings.TrimPrefix(p.Path, "sngl:")+"/*.sngl")
		if err != nil {
			return nil, err
		}
		for _, file := range files {
			disk := filepath.Join(root, "lib", filepath.FromSlash(file))
			src, err := os.ReadFile(disk)
			if err != nil {
				return nil, err
			}
			out, err := Rewrite(src, byFile[file])
			if err != nil {
				return nil, fmt.Errorf("%s: %w", disk, err)
			}
			plan.Sources[disk] = out
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil && !os.IsNotExist(err) {
		return nil, err
	}
	for _, e := range entries {
		if _, ok := plan.Files[e.Name()]; ok || e.IsDir() {
			continue
		}
		if data, err := os.ReadFile(filepath.Join(dir, e.Name())); err == nil && bytes.HasPrefix(data, []byte(header)) {
			plan.Stale = append(plan.Stale, e.Name())
		}
	}
	return plan, nil
}

// Write writes p.
func (p *Plan) Write() error {
	if err := os.MkdirAll(p.Dir, 0o755); err != nil {
		return err
	}
	for name, data := range p.Files {
		if err := os.WriteFile(filepath.Join(p.Dir, name), data, 0o644); err != nil {
			return err
		}
	}
	for _, name := range p.Stale {
		if err := os.Remove(filepath.Join(p.Dir, name)); err != nil {
			return err
		}
	}
	for disk, data := range p.Sources {
		if err := os.WriteFile(disk, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// goImportPath is dir's Go import path: the module of the nearest go.mod
// above it and the path from there.
func goImportPath(dir string) (string, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return "", err
	}
	for d := abs; ; d = filepath.Dir(d) {
		data, err := os.ReadFile(filepath.Join(d, "go.mod"))
		if err == nil {
			mod := modulePath(data)
			if mod == "" {
				return "", fmt.Errorf("%s/go.mod names no module", d)
			}
			rel, err := filepath.Rel(d, abs)
			if err != nil {
				return "", err
			}
			return path.Join(mod, filepath.ToSlash(rel)), nil
		}
		if filepath.Dir(d) == d {
			return "", fmt.Errorf("no go.mod above %s", dir)
		}
	}
}

func modulePath(gomod []byte) string {
	sc := bufio.NewScanner(bytes.NewReader(gomod))
	for sc.Scan() {
		if f := strings.Fields(sc.Text()); len(f) == 2 && f[0] == "module" {
			return strings.Trim(f[1], `"`)
		}
	}
	return ""
}
