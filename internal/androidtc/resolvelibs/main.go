// Command resolvelibs resolves the libraries a gradle-free android build
// compiles and dexes against, for every combo, and writes them with their
// SHA-256 to internal/androidtc/libs_gen.go.
//
//	go run ./internal/androidtc/resolvelibs
//
// The roots are what the Gradle scaffold declares (Combo.LibraryRoots), and
// the closure is resolved the way Gradle resolves it: through each module's
// Gradle module metadata where it publishes one, taking its Android runtime
// variant (or the JVM one) and following a Kotlin multiplatform root to the
// module that variant is available at; through the POM where it does not;
// counting the compose BOM's versions and every module's dependency
// constraints; and taking the highest version a module is asked for. The
// Kotlin standard library is left out: the kotlinc distribution carries it.
//
// It talks to Google's Maven repository and Maven Central, so it is run by
// hand when a combo changes, never by a test.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"encoding/xml"
	"errors"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"duckfam.us/sngl/internal/androidtc"
)

var repos = []string{
	"https://dl.google.com/dl/android/maven2/",
	"https://repo1.maven.org/maven2/",
}

func main() {
	log.SetFlags(0)
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by go run ./internal/androidtc/resolvelibs; DO NOT EDIT.

package androidtc

var comboLibs = map[string][]Lib{
`)
	for _, c := range androidtc.Combos() {
		libs, err := resolve(c)
		if err != nil {
			log.Fatalf("combo %s: %v", c.Name, err)
		}
		fmt.Fprintf(&buf, "\t%q: {\n", c.Name)
		for _, l := range libs {
			fmt.Fprintf(&buf, "\t\t{Group: %q, Module: %q, Version: %q, File: %q, URL: %q, SHA256: %q},\n",
				l.Group, l.Module, l.Version, l.File, l.URL, l.SHA256)
		}
		buf.WriteString("\t},\n")
		log.Printf("%s: %d libraries", c.Name, len(libs))
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	out := filepath.Join("internal", "androidtc", "libs_gen.go")
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// coord is a module without its version.
type coord struct{ group, module string }

func (c coord) String() string { return c.group + ":" + c.module }

// provided is what the build has without a download.
func provided(c coord) bool {
	return c.group == "org.jetbrains.kotlin" && strings.HasPrefix(c.module, "kotlin-stdlib")
}

// meta is what one version of a module says: what it depends on, what it
// constrains, the module its Android variant is available at, and its file.
type meta struct {
	deps        []req
	constraints []req
	redirect    *req
	file        string // name beside the module, "" for none
	url         string
	sha256      string
}

type req struct {
	coord
	version string
}

func resolve(c androidtc.Combo) ([]androidtc.Lib, error) {
	roots, bom := c.LibraryRoots()
	bomVersions := map[coord]string{}
	if bom != "" {
		g, m, v := split3(bom)
		managed, err := pomManaged(g, m, v)
		if err != nil {
			return nil, fmt.Errorf("BOM %s: %w", bom, err)
		}
		bomVersions = managed
	}
	var rootReqs []req
	for _, r := range roots {
		g, m, v := split3(r)
		rq := req{coord{g, m}, v}
		if rq.version == "" {
			rq.version = bomVersions[rq.coord]
			if rq.version == "" {
				return nil, fmt.Errorf("root %s has no version and the BOM names none", r)
			}
		}
		rootReqs = append(rootReqs, rq)
	}

	selected := map[coord]string{}
	for {
		asked := map[coord][]string{}
		for c, v := range bomVersions {
			asked[c] = append(asked[c], v)
		}
		seen := map[coord]bool{}
		queue := append([]req(nil), rootReqs...)
		for _, r := range rootReqs {
			asked[r.coord] = append(asked[r.coord], r.version)
		}
		for len(queue) > 0 {
			r := queue[0]
			queue = queue[1:]
			if seen[r.coord] || provided(r.coord) {
				continue
			}
			seen[r.coord] = true
			v := selected[r.coord]
			if v == "" {
				v = r.version
			}
			m, err := fetchMeta(r.group, r.module, v)
			if err != nil {
				return nil, fmt.Errorf("%s:%s: %w", r.coord, v, err)
			}
			for _, d := range m.constraints {
				asked[d.coord] = append(asked[d.coord], d.version)
			}
			next := m.deps
			if m.redirect != nil {
				next = append(next, *m.redirect)
			}
			for _, d := range next {
				asked[d.coord] = append(asked[d.coord], d.version)
				queue = append(queue, d)
			}
		}
		changed := false
		for c := range seen {
			best := selected[c]
			for _, v := range asked[c] {
				if best == "" || compareVersions(v, best) > 0 {
					best = v
				}
			}
			if best != selected[c] {
				selected[c] = best
				changed = true
			}
		}
		if !changed {
			var libs []androidtc.Lib
			for c := range seen {
				m, err := fetchMeta(c.group, c.module, selected[c])
				if err != nil {
					return nil, err
				}
				if m.file == "" {
					continue
				}
				libs = append(libs, androidtc.Lib{
					Group: c.group, Module: c.module, Version: selected[c],
					File: m.file, URL: m.url, SHA256: m.sha256,
				})
			}
			sort.Slice(libs, func(i, j int) bool {
				if libs[i].Group != libs[j].Group {
					return libs[i].Group < libs[j].Group
				}
				return libs[i].Module < libs[j].Module
			})
			return libs, nil
		}
	}
}

var metaCache = map[string]*meta{}

func fetchMeta(group, module, version string) (*meta, error) {
	key := group + ":" + module + ":" + version
	if m, ok := metaCache[key]; ok {
		return m, nil
	}
	base := strings.ReplaceAll(group, ".", "/") + "/" + module + "/" + version + "/"
	stem := module + "-" + version
	var m *meta
	data, repo, err := get(base + stem + ".module")
	if err == nil {
		m, err = fromModule(data, repo+base)
	} else if errors.Is(err, errNotFound) {
		m, err = fromPOM(group, module, version)
	}
	if err != nil {
		return nil, err
	}
	metaCache[key] = m
	return m, nil
}

// moduleFile is the subset of Gradle module metadata this reads.
type moduleFile struct {
	Variants []struct {
		Name        string             `json:"name"`
		Attributes  map[string]any     `json:"attributes"`
		AvailableAt *availableAt       `json:"available-at"`
		Deps        []moduleDependency `json:"dependencies"`
		Constraints []moduleDependency `json:"dependencyConstraints"`
		Files       []struct {
			Name   string `json:"name"`
			URL    string `json:"url"`
			SHA256 string `json:"sha256"`
		} `json:"files"`
	} `json:"variants"`
}

type moduleDependency struct {
	Group      string         `json:"group"`
	Module     string         `json:"module"`
	URL        string         `json:"url"`
	Attributes map[string]any `json:"attributes"`
	Version    struct {
		Requires string `json:"requires"`
		Strictly string `json:"strictly"`
		Prefers  string `json:"prefers"`
	} `json:"version"`
}

func (d moduleDependency) req() req {
	v := d.Version.Strictly
	if v == "" {
		v = d.Version.Requires
	}
	if v == "" {
		v = d.Version.Prefers
	}
	return req{coord{d.Group, d.Module}, v}
}

// fromModule picks the runtime variant an Android app's build takes: the
// androidJvm one where there is one, else the JVM one.
func fromModule(data []byte, dir string) (*meta, error) {
	var mf moduleFile
	if err := json.Unmarshal(data, &mf); err != nil {
		return nil, err
	}
	best, bestRank := -1, 0
	for i, v := range mf.Variants {
		a := v.Attributes
		if a["org.gradle.usage"] != "java-runtime" || a["org.gradle.category"] != "library" {
			continue
		}
		if a["org.gradle.jvm.environment"] == "non-jvm" {
			continue
		}
		rank := 1
		switch a["org.jetbrains.kotlin.platform.type"] {
		case "androidJvm":
			rank = 3
		case "jvm", nil:
			rank = 2
			if a["org.gradle.jvm.environment"] == "android" {
				rank = 3
			}
		default:
			continue
		}
		if rank > bestRank {
			best, bestRank = i, rank
		}
	}
	if best < 0 {
		return nil, fmt.Errorf("no runtime variant for an android app")
	}
	v := mf.Variants[best]
	m := &meta{}
	if v.AvailableAt != nil {
		a := v.AvailableAt
		m.redirect = &req{coord{a.Group, a.Module}, a.Version}
		return m, nil
	}
	for _, d := range v.Deps {
		// A platform (a BOM) is not a library: what it contributes is its
		// constraints, which Gradle applies to the graph as any other.
		if d.Attributes["org.gradle.category"] == "platform" {
			cs, err := platformConstraints(d.req())
			if err != nil {
				return nil, fmt.Errorf("platform %s: %w", d.req().coord, err)
			}
			m.constraints = append(m.constraints, cs...)
			continue
		}
		m.deps = append(m.deps, d.req())
	}
	for _, d := range v.Constraints {
		m.constraints = append(m.constraints, d.req())
	}
	for _, f := range v.Files {
		if strings.HasSuffix(f.Name, ".aar") || strings.HasSuffix(f.Name, ".jar") {
			m.file, m.url, m.sha256 = f.Name, dir+f.URL, f.SHA256
			break
		}
	}
	return m, nil
}

type pom struct {
	Packaging string `xml:"packaging"`
	Deps      []struct {
		Group    string `xml:"groupId"`
		Artifact string `xml:"artifactId"`
		Version  string `xml:"version"`
		Scope    string `xml:"scope"`
		Optional string `xml:"optional"`
		Type     string `xml:"type"`
	} `xml:"dependencies>dependency"`
	Managed []struct {
		Group    string `xml:"groupId"`
		Artifact string `xml:"artifactId"`
		Version  string `xml:"version"`
	} `xml:"dependencyManagement>dependencies>dependency"`
}

func readPOM(group, module, version string) (*pom, string, error) {
	base := strings.ReplaceAll(group, ".", "/") + "/" + module + "/" + version + "/"
	data, repo, err := get(base + module + "-" + version + ".pom")
	if err != nil {
		return nil, "", err
	}
	var p pom
	if err := xml.Unmarshal(data, &p); err != nil {
		return nil, "", err
	}
	return &p, repo + base, nil
}

func pomManaged(group, module, version string) (map[coord]string, error) {
	p, _, err := readPOM(group, module, version)
	if err != nil {
		return nil, err
	}
	out := map[coord]string{}
	for _, d := range p.Managed {
		out[coord{d.Group, d.Artifact}] = d.Version
	}
	return out, nil
}

func fromPOM(group, module, version string) (*meta, error) {
	p, dir, err := readPOM(group, module, version)
	if err != nil {
		return nil, err
	}
	m := &meta{}
	for _, d := range p.Deps {
		if d.Optional == "true" || (d.Scope != "" && d.Scope != "compile" && d.Scope != "runtime") {
			continue
		}
		if d.Version == "" || strings.Contains(d.Version, "${") {
			return nil, fmt.Errorf("dependency %s:%s names no version this reads", d.Group, d.Artifact)
		}
		m.deps = append(m.deps, req{coord{d.Group, d.Artifact}, strings.Trim(d.Version, "[]")})
	}
	ext := "jar"
	if p.Packaging == "aar" {
		ext = "aar"
	}
	if p.Packaging == "pom" {
		return m, nil
	}
	name := module + "-" + version + "." + ext
	data, _, err := get(strings.TrimPrefix(dir, repoOf(dir)) + name)
	if err != nil {
		return nil, err
	}
	s := sha256.Sum256(data)
	m.file, m.url, m.sha256 = name, dir+name, hex.EncodeToString(s[:])
	return m, nil
}

func repoOf(url string) string {
	for _, r := range repos {
		if strings.HasPrefix(url, r) {
			return r
		}
	}
	return ""
}

var errNotFound = errors.New("not found")

// get fetches path from the first repository that has it.
func get(path string) ([]byte, string, error) {
	for _, repo := range repos {
		resp, err := http.Get(repo + path)
		if err != nil {
			return nil, "", err
		}
		data, err := io.ReadAll(resp.Body)
		resp.Body.Close()
		if err != nil {
			return nil, "", err
		}
		if resp.StatusCode == http.StatusOK {
			return data, repo, nil
		}
		if resp.StatusCode != http.StatusNotFound {
			return nil, "", fmt.Errorf("%s%s: HTTP %d", repo, path, resp.StatusCode)
		}
	}
	return nil, "", fmt.Errorf("%s: %w", path, errNotFound)
}

// compareVersions orders two Maven versions the way Gradle does for the
// versions these libraries publish: numerically by part, and a release after
// its alphas, betas and release candidates.
func compareVersions(a, b string) int {
	pa, pb := versionParts(a), versionParts(b)
	for i := 0; i < max(len(pa), len(pb)); i++ {
		var x, y string
		if i < len(pa) {
			x = pa[i]
		}
		if i < len(pb) {
			y = pb[i]
		}
		if c := comparePart(x, y); c != 0 {
			return c
		}
	}
	return 0
}

func versionParts(v string) []string {
	return strings.FieldsFunc(v, func(r rune) bool { return r == '.' || r == '-' || r == '+' || r == '_' })
}

var qualifierRank = map[string]int{"dev": 0, "alpha": 1, "beta": 2, "rc": 3, "": 4}

func comparePart(x, y string) int {
	nx, ex := strconv.Atoi(x)
	ny, ey := strconv.Atoi(y)
	switch {
	case ex == nil && ey == nil:
		return cmpInt(nx, ny)
	case ex == nil && y == "":
		return cmpInt(nx, 0)
	case ey == nil && x == "":
		return cmpInt(0, ny)
	case ex == nil:
		return 1 // a number is newer than a qualifier
	case ey == nil:
		return -1
	}
	rx, okx := qualifierRank[strings.TrimRight(strings.ToLower(x), "0123456789")]
	ry, oky := qualifierRank[strings.TrimRight(strings.ToLower(y), "0123456789")]
	if okx && oky && rx != ry {
		return cmpInt(rx, ry)
	}
	return strings.Compare(x, y)
}

func cmpInt(a, b int) int {
	switch {
	case a < b:
		return -1
	case a > b:
		return 1
	}
	return 0
}

// split3 splits group:module[:version].
func split3(s string) (group, module, version string) {
	parts := strings.SplitN(s, ":", 3)
	for len(parts) < 3 {
		parts = append(parts, "")
	}
	return parts[0], parts[1], parts[2]
}

type availableAt struct {
	Group   string `json:"group"`
	Module  string `json:"module"`
	Version string `json:"version"`
}

// platformConstraints are the versions a platform module (a BOM) sets: its
// platform variant's dependency constraints, or its POM's managed
// dependencies where it publishes no module metadata.
func platformConstraints(p req) ([]req, error) {
	base := strings.ReplaceAll(p.group, ".", "/") + "/" + p.module + "/" + p.version + "/"
	data, _, err := get(base + p.module + "-" + p.version + ".module")
	if errors.Is(err, errNotFound) {
		managed, err := pomManaged(p.group, p.module, p.version)
		if err != nil {
			return nil, err
		}
		var out []req
		for c, v := range managed {
			out = append(out, req{c, v})
		}
		return out, nil
	}
	if err != nil {
		return nil, err
	}
	var mf moduleFile
	if err := json.Unmarshal(data, &mf); err != nil {
		return nil, err
	}
	var out []req
	for _, v := range mf.Variants {
		if v.Attributes["org.gradle.category"] != "platform" || v.Attributes["org.gradle.usage"] != "java-runtime" {
			continue
		}
		for _, d := range v.Constraints {
			out = append(out, d.req())
		}
	}
	return out, nil
}
